import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { buildApp } from '../src/app.js';
import { openDatabase } from '../src/db.js';
import { createOwner } from '../src/auth.js';
import type { AppConfig } from '../src/config.js';

const origin='http://localhost:5173';
test('spatial API: migrations, revision checks, owner protection, link/unlink, restart', async () => {
  const dir=mkdtempSync(path.join(os.tmpdir(),'notetaking-pages-'));
  const filename=path.join(dir,'state.sqlite');
  const config:AppConfig={appOrigin:origin,databasePath:filename,host:'127.0.0.1',port:3000,isProduction:false};
  let db=openDatabase(filename);
  let app=await buildApp({db,config});
  const request=async (method:string,url:string,payload?:unknown,cookie?:string,reqOrigin=origin)=>
    app.inject({method,url,headers:{...(method!=='GET'?{origin:reqOrigin}:{}),...(cookie?{cookie}:{})},
      ...(payload===undefined?{}:{payload})});
  try {
    await app.ready();
    assert.equal((db.prepare('SELECT COUNT(*) AS n FROM schema_migrations').get() as {n:number}).n,4);
    await createOwner(db,'test-long-password-987');
    const login=await request('POST','/api/auth/login',{password:'test-long-password-987'});
    const cookie=String(login.headers['set-cookie']).split(';')[0];
    assert.ok(cookie);
    const f=await request('POST','/api/folders',{name:'Research'},cookie);
    assert.equal(f.statusCode,201);
    const folderId=f.json().folder.id as string;
    const n=await request('POST','/api/notes',{title:'Lecture',folderId},cookie);
    const noteId=n.json().note.id as string;
    const other=await request('POST','/api/notes',{title:'Other',folderId},cookie);
    const otherId=other.json().note.id as string;
    const base='/api/notes/'+noteId+'/pages';
    assert.equal((await request('GET',base)).statusCode,401);
    assert.equal((await request('POST',base+'/initialize',{expectedVersion:0})).statusCode,401);
    assert.equal((await request('POST',base+'/initialize',{expectedVersion:0},cookie,'https://evil.example')).statusCode,403);
    const empty=await request('GET',base,undefined,cookie);
    assert.equal(empty.statusCode,200);
    assert.equal(empty.json().version,0);
    assert.equal(empty.json().pages.length,0);
    const initialized=await request('POST',base+'/initialize',{expectedVersion:0},cookie);
    assert.equal(initialized.statusCode,200,initialized.body);
    const A=initialized.json().pages[0].id as string;
    assert.equal(initialized.json().version,1);
    assert.equal((await request('POST',base+'/initialize',{expectedVersion:1},cookie)).statusCode,409);
    const otherInit=await request('POST','/api/notes/'+otherId+'/pages/initialize',{expectedVersion:0},cookie);
    assert.equal(otherInit.json().pages[0].gx,0);
    assert.notEqual(otherInit.json().pages[0].id,A);
    assert.equal((await request('POST',base+'/insert',{anchorId:A,direction:'N',expectedVersion:0},cookie)).statusCode,409);
    assert.equal((await request('POST',base+'/preview',{anchorId:A,direction:'bad',expectedVersion:1},cookie)).statusCode,400);
    const preview=await request('POST',base+'/preview',{anchorId:A,direction:'E',expectedVersion:1},cookie);
    assert.equal(preview.statusCode,200,preview.body);
    assert.equal(preview.json().plan.shifts.length,0);
    assert.equal(preview.json().plan.gx,1);
    const created=await request('POST',base+'/insert',{anchorId:A,direction:'E',expectedVersion:1},cookie);
    assert.equal(created.statusCode,200,created.body);
    const B=created.json().pages.find((p:{id:string})=>p.id!==A).id as string;
    assert.equal(created.json().version,2);
    assert.equal(created.json().edges.length,1);
    assert.equal((await request('POST',base+'/insert',{anchorId:A,direction:'E',expectedVersion:1},cookie)).statusCode,409);
    const between=await request('POST',base+'/preview',{anchorId:A,direction:'E',expectedVersion:2},cookie);
    assert.deepEqual(between.json().plan.shifts.map((p:{id:string;gx:number})=>[p.id,p.gx]),[[B,2]]);
    const committed=await request('POST',base+'/insert',{anchorId:A,direction:'E',expectedVersion:2},cookie);
    assert.equal(committed.statusCode,200,committed.body);
    assert.equal(committed.json().pages.length,3);
    assert.equal(committed.json().edges.length,2);
    assert.equal((await request('POST',base+'/link',{fromPageId:A,toPageId:B,direction:'E',expectedVersion:3},cookie)).statusCode,409);
    const middle=committed.json().pages.find((p:{id:string})=>p.id!==A&&p.id!==B).id as string;
    assert.equal((await request('DELETE',base+'/'+middle,{expectedVersion:3},cookie)).statusCode,409);
    assert.equal((await request('DELETE',base+'/'+B,{expectedVersion:3},cookie)).statusCode,200);
    assert.equal((await request('POST',base+'/unlink',{fromPageId:A,direction:'E',expectedVersion:4},cookie)).statusCode,200);
    assert.equal((await request('POST',base+'/link',{fromPageId:A,toPageId:middle,direction:'E',expectedVersion:5},cookie)).statusCode,200);
    await app.close();
    db.close();
    db=openDatabase(filename);
    app=await buildApp({db,config});
    await app.ready();
    const reloaded=await request('GET',base,undefined,cookie);
    assert.equal(reloaded.statusCode,200);
    assert.equal(reloaded.json().version,6);
    assert.equal(reloaded.json().pages.length,2);
    assert.equal((await request('GET','/api/notes/'+otherId+'/pages',undefined,cookie)).json().pages.length,1);
  } finally {
    await app.close();
    db.close();
    rmSync(dir,{recursive:true,force:true});
  }
});
